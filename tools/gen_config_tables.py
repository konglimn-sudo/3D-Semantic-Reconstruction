"""Generates cpp/gr/io/config_tables.inc: the YAML key -> member tables of
the C++ config structs (gr/io/config.h FieldTable), from the pybind11
bindings. The bindings name every field after its YAML key (that is what
core_config.fill relies on), so the C++ programs read a configuration
exactly as the Python stages do.

    python3 tools/gen_config_tables.py          # writes the file
    python3 tools/gen_config_tables.py --check  # fails if it is stale
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
BINDINGS = sorted((ROOT / "cpp" / "bindings").glob("bind_*.cc"))
OUT = ROOT / "cpp" / "gr" / "io" / "config_tables.inc"
# Structs read from YAML sections; nested struct members (e.g.
# OdometryConfig::lio) are filled separately and skipped here.
STRUCTS = ("OdometryConfig", "LioConfig", "KeyframeConfig", "LoopConfig",
           "AppearanceLoopConfig", "BackendConfig", "TripAlignConfig",
           "RefineConfig", "LidarBaConfig", "MapFusionConfig",
           "DynamicConfig", "LevelConfig", "LocalizerConfig",
           "PlacementConfig", "SlotStateConfig", "ChangeConfig",
           "LidarImuConfig")
NESTED = {"OdometryConfig": {"lio"}, "LocalizerConfig": {"placement"}}


def fields(struct: str) -> list[tuple[str, str]]:
    """(key, member) pairs of a struct's def_readwrite in the bindings."""
    for path in BINDINGS:
        text = path.read_text()
        start = text.find(f'py::class_<{struct}>(m, "{struct}")')
        if start < 0:
            continue
        end = text.find(";", start)
        body = text[start:end]
        found = re.findall(
            r'def_readwrite\(\s*"(\w+)",\s*&' + struct + r'::(\w+)\)', body)
        return [(k, m) for k, m in found if k not in NESTED.get(struct, ())]
    raise KeyError(f"{struct} is not bound")


def generate() -> str:
    lines = ["// Generated by tools/gen_config_tables.py from the bindings; do",
             "// not edit. YAML key -> member of each config struct.", ""]
    for struct in STRUCTS:
        lines.append(f"inline const FieldTable<{struct}>& {struct}Fields() {{")
        lines.append(f"  static const FieldTable<{struct}> table =")
        lines.append(f"      FieldTable<{struct}>()")
        pairs = fields(struct)
        for k, (key, member) in enumerate(pairs):
            end = ";" if k == len(pairs) - 1 else ""
            line = f'          .Add("{key}", &{struct}::{member}){end}'
            if len(line) > 80:  # Google style: 80 columns.
                lines.append(f'          .Add("{key}",')
                line = f"               &{struct}::{member}){end}"
            lines.append(line)
        if not pairs:
            lines[-1] += ";"
        lines.append("  return table;")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run tools/gen_config_tables.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
